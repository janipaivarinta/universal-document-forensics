#!/usr/bin/env python3
"""Universal Office & PDF Forensics 1.3 (Python 3.9+).
Read-only, local analysis. Optional: pip install olefile pypdf
Reports classify technical evidence and document its significance.
"""
import argparse
import collections
import hashlib
import pathlib
import re
import sys
import zipfile
import xml.etree.ElementTree as ET
from datetime import datetime

EXTENSIONS = {'.doc', '.docx', '.xls', '.xlsx', '.ppt', '.pptx', '.pdf'}
ZIP_FORMATS = {'.docx': 'word/document.xml', '.xlsx': 'xl/workbook.xml', '.pptx': 'ppt/presentation.xml'}
OLE_MAGIC = bytes.fromhex('D0CF11E0A1B11AE1')
W = '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
MAX_PART = 32 * 1024 * 1024
MAX_TOTAL = 512 * 1024 * 1024
MAX_ENTRIES = 10000
MAX_FINDINGS = 150
MARKERS = {
    'python-docx': 'Document generation library', 'python-pptx': 'Presentation generation library',
    'openpyxl': 'Spreadsheet processing library', 'xlsxwriter': 'Spreadsheet generation library',
    'xlwt': 'Legacy spreadsheet generation library', 'reportlab': 'PDF generation library',
    'pypdf': 'PDF processing library', 'pymupdf': 'PDF processing library',
    'pandoc': 'Document conversion software', 'libreoffice': 'Office software',
    'aspose': 'Programmatic document processing', 'docx4j': 'Document processing library',
    'mammoth': 'Document conversion library', 'chatgpt': 'AI service name',
    'openai': 'AI provider or integration name', 'copilot': 'AI assistant or product name',
    'gemini': 'AI service name', 'claude': 'AI service name', 'ollama': 'Local LLM runtime name',
}
AI_MARKERS = {'chatgpt', 'openai', 'copilot', 'gemini', 'claude', 'ollama'}


def local(tag):
    return str(tag).rsplit('}', 1)[-1]


def tidy(value, limit=300):
    s = ''.join(c if c.isprintable() else ' ' for c in str('' if value is None else value))
    return s[:limit] + (' [TRUNCATED]' if len(s) > limit else '')


def sha256(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def finding(result, marker, part, field, value, start=0):
    if len(result['findings']) >= MAX_FINDINGS:
        result['findings_truncated'] = True
        return
    metadata = part.startswith('docProps/') or part.startswith('OLE metadata') or part.startswith('PDF metadata')
    generated = bool(re.search(r'\b(generated|created|produced)\s+by\s+' + re.escape(marker) + r'\b', str(value), re.I))
    if marker in AI_MARKERS:
        level = 'AI-related name in metadata' if metadata else 'AI-related name/reference'
        interpretation = ('AI-related identifier recorded in metadata.' if metadata else 'AI-related identifier recorded in document content or structure. Its location determines evidentiary relevance.')
    elif metadata and generated:
        level = 'STRONG: Explicit programmatic generation attribution'
        interpretation = ('The metadata explicitly states that this file was generated by ' + marker + '. This is strong technical evidence of a programmatic generation workflow using that library or software. The statement identifies the technology, not the operator or the origin of the code.')
    elif metadata:
        level = 'SIGNIFICANT: Software identifier in metadata'
        interpretation = ('The metadata explicitly records ' + marker + ' in the ' + field + ' field. This is a significant technical indicator associating the file with that software. The field and other recorded evidence determine whether it identifies the generating application or a later processing step.')
    else:
        level = 'Software string/reference'
        interpretation = ('The file contains the identifier ' + marker + ' at the specified location. If this is an application or producer field it supports software attribution; if it is ordinary document text it records a mention rather than a generation event.')
    excerpt = str(value)[max(0, start - 85):start + len(marker) + 85]
    result['findings'].append(dict(marker=marker, description=MARKERS[marker], location=part,
                                   field=field, context=tidy(excerpt, 190), level=level,
                                   interpretation=interpretation))


def scan_value(result, part, field, value):
    s = str('' if value is None else value)
    for marker in MARKERS:
        for match in list(re.finditer(re.escape(marker), s, re.I))[:3]:
            finding(result, marker, part, field, s, match.start())


def xml_read(z, name, result):
    try:
        info = z.getinfo(name)
        if info.file_size > MAX_PART:
            result['warnings'].append('Skipped oversized XML part: ' + name)
            return None
        return ET.fromstring(z.read(info))
    except KeyError:
        return None
    except (ET.ParseError, ValueError, RuntimeError, zipfile.BadZipFile) as exc:
        result['warnings'].append('XML read failed for ' + name + ': ' + tidy(exc))
        return None


def metadata_xml(root, custom=False):
    if root is None:
        return {}
    out = {}
    for el in root:
        key = el.attrib.get('name', local(el.tag)) if custom else local(el.tag)
        out[key] = tidy(' '.join(x.text for x in el.iter() if x.text), 1000)
    return out


def inspect_ooxml(path, result):
    if not zipfile.is_zipfile(path):
        result['warnings'].append('Not a valid ZIP container for this extension.')
        return
    with zipfile.ZipFile(path) as z:
        entries = z.infolist()
        total = sum(e.file_size for e in entries)
        result['integrity'].update(zip_entries=len(entries), uncompressed_bytes=total,
                                   duplicate_names=len(entries)-len(set(e.filename for e in entries)),
                                   compression_types=dict(collections.Counter(e.compress_type for e in entries)))
        if len(entries) > MAX_ENTRIES or total > MAX_TOTAL:
            result['warnings'].append('Archive safety limits exceeded; content inspection stopped.')
            return
        try:
            result['integrity']['crc_failure'] = z.testzip() or 'None detected'
        except (RuntimeError, zipfile.BadZipFile, OSError) as exc:
            result['integrity']['crc_failure'] = tidy(exc)
        names = set(z.namelist())
        main = ZIP_FORMATS[path.suffix.lower()]
        result['structure']['required_parts'] = {n: n in names for n in ('[Content_Types].xml', '_rels/.rels', main)}
        result['structure']['optional_parts'] = {n: n in names for n in ('docProps/core.xml','docProps/app.xml','docProps/custom.xml')}
        for n in ('docProps/core.xml', 'docProps/app.xml', 'docProps/custom.xml'):
            root = xml_read(z, n, result)
            result['metadata'][n] = metadata_xml(root, n.endswith('custom.xml'))
        suffix = path.suffix.lower()
        if suffix == '.docx':
            doc = xml_read(z, main, result)
            settings = xml_read(z, 'word/settings.xml', result)
            if doc is not None:
                tags = collections.Counter(local(e.tag) for e in doc.iter())
                result['structure']['word_elements'] = {k: tags[k] for k in ('p','tbl','r','hyperlink','ins','del','moveFrom','moveTo','commentReference')}
                result['structure']['top_paragraph_styles'] = collections.Counter(e.attrib.get(W+'val') for e in doc.iter() if e.tag == W+'pStyle').most_common(10)
                used = collections.Counter(local(k) for e in doc.iter() for k in e.attrib if k.startswith(W+'rsid'))
                values = {v for e in doc.iter() for k,v in e.attrib.items() if k.startswith(W+'rsid')}
                registered = {e.attrib[W+'val'] for e in settings.iter() if e.tag == W+'rsid' and W+'val' in e.attrib} if settings is not None else set()
                result['structure']['rsid'] = dict(attributes=sum(used.values()), types=dict(used), unique_used=len(values),
                                                    registered=len(registered), used_not_registered=len(values-registered))
            result['structure']['word_parts'] = {n: n in names for n in ('word/settings.xml','word/styles.xml','word/comments.xml','word/numbering.xml')}
        elif suffix == '.xlsx':
            result['structure']['worksheets'] = len([n for n in names if re.fullmatch(r'xl/worksheets/sheet\d+\.xml', n)])
            result['structure']['shared_strings_present'] = 'xl/sharedStrings.xml' in names
            result['structure']['external_link_parts'] = len([n for n in names if n.startswith('xl/externalLinks/') and n.endswith('.xml')])
            result['structure']['formula_elements'] = 0
            result['structure']['sheet_names'] = []
            root = xml_read(z, main, result)
            if root is not None:
                result['structure']['sheet_names'] = [tidy(e.attrib.get('name'), 100) for e in root.iter() if local(e.tag) == 'sheet'][:100]
        else:
            result['structure']['slides'] = len([n for n in names if re.fullmatch(r'ppt/slides/slide\d+\.xml', n)])
            result['structure']['notes_slides'] = len([n for n in names if re.fullmatch(r'ppt/notesSlides/notesSlide\d+\.xml', n)])
            result['structure']['comment_parts'] = len([n for n in names if 'comment' in n.lower() and n.endswith('.xml')])
        result['structure']['embedded_object_parts'] = len([n for n in names if '/embeddings/' in n])
        result['structure']['macro_parts'] = [n for n in sorted(names) if n.lower().endswith('vbaproject.bin')][:20]
        for info in entries:
            name = info.filename
            if not name.lower().endswith(('.xml','.rels')):
                continue
            root = xml_read(z, name, result)
            if root is None:
                continue
            if suffix == '.xlsx' and re.fullmatch(r'xl/worksheets/sheet\d+\.xml', name):
                result['structure']['formula_elements'] += sum(local(e.tag) == 'f' for e in root.iter())
            for el in root.iter():
                if el.text:
                    scan_value(result, name, local(el.tag), el.text)
                for key, val in el.attrib.items():
                    scan_value(result, name, '@'+local(key), val)


def inspect_ole(path, result):
    with path.open('rb') as f:
        if f.read(8) != OLE_MAGIC:
            result['warnings'].append('OLE compound-file signature is missing.')
            return
    try:
        import olefile
    except ImportError:
        result['warnings'].append('Install optional olefile package for full OLE stream and property inspection: python3 -m pip install olefile')
        # Bounded raw string search is not a substitute for parsing OLE streams.
        with path.open('rb') as f:
            raw = f.read(min(path.stat().st_size, 8 * 1024 * 1024))
        for encoding, label in (('latin1','raw bytes'),('utf-16le','UTF-16LE bytes')):
            text = raw.decode(encoding, errors='ignore')
            scan_value(result, 'Unparsed OLE '+label, 'raw string', text[:4000000])
        return
    with olefile.OleFileIO(str(path)) as ole:
        streams = ole.listdir()
        result['structure']['ole_streams'] = ['/'.join(s) for s in streams[:200]]
        result['structure']['ole_stream_count'] = len(streams)
        for name in ('\x05SummaryInformation', '\x05DocumentSummaryInformation'):
            if ole.exists(name):
                try:
                    props = ole.getproperties(name)
                    result['metadata']['OLE metadata '+name] = {str(k): tidy(v, 1000) for k,v in props.items()}
                except Exception as exc:
                    result['warnings'].append('OLE properties unreadable: '+tidy(exc))
        for section, fields in result['metadata'].items():
            for key, value in fields.items():
                scan_value(result, 'OLE metadata '+section, key, value)
        for stream in streams:
            name = '/'.join(stream)
            try:
                size = ole.get_size(stream)
                if size > MAX_PART:
                    result['warnings'].append('Skipped oversized OLE stream: '+name)
                    continue
                raw = ole.openstream(stream).read()
                for enc in ('latin1','utf-16le'):
                    scan_value(result, 'OLE stream '+name, enc, raw.decode(enc, errors='ignore')[:4000000])
            except Exception as exc:
                result['warnings'].append('OLE stream error '+name+': '+tidy(exc))


def inspect_pdf(path, result):
    with path.open('rb') as f:
        head = f.read(1024)
        f.seek(max(0, path.stat().st_size - 4096))
        tail = f.read()
    result['integrity']['pdf_header'] = bool(re.search(rb'%PDF-\d\.\d', head))
    result['integrity']['eof_marker_near_end'] = b'%%EOF' in tail
    try:
        from pypdf import PdfReader
    except ImportError:
        result['warnings'].append('Install optional pypdf for PDF metadata, pages and structure: python3 -m pip install pypdf')
        # Only shallow binary inspection without parser.
        with path.open('rb') as f:
            raw = f.read(min(path.stat().st_size, 8*1024*1024))
        scan_value(result, 'PDF raw bytes (unparsed)', 'text', raw.decode('latin1', errors='ignore'))
        return
    try:
        reader = PdfReader(str(path), strict=False)
        result['integrity']['encrypted'] = reader.is_encrypted
        if reader.is_encrypted:
            result['warnings'].append('Encrypted PDF: content inspection may be unavailable.')
            try:
                if not reader.decrypt(''):
                    return
            except Exception:
                return
        result['structure']['pages'] = len(reader.pages)
        result['structure']['attachments'] = []
        try:
            result['structure']['attachments'] = [tidy(k, 150) for k in reader.attachments.keys()][:100]
        except Exception:
            pass
        meta = reader.metadata
        if meta:
            result['metadata']['PDF metadata'] = {str(k): tidy(v, 1000) for k,v in meta.items()}
            for key, value in meta.items():
                scan_value(result, 'PDF metadata', str(key), str(value))
        try:
            xmp = reader.xmp_metadata
            if xmp is not None:
                for attr in ('dc_creator','dc_title','dc_description','xmp_creator_tool','xmp_create_date','xmp_modify_date','pdf_producer'):
                    try:
                        value = getattr(xmp, attr, None)
                        if value is not None:
                            result['metadata'].setdefault('PDF XMP metadata', {})[attr] = tidy(value, 1000)
                            scan_value(result, 'PDF metadata XMP', attr, value)
                    except Exception:
                        pass
        except Exception as exc:
            result['warnings'].append('XMP parsing issue: '+tidy(exc))
        result['structure']['page_text_scanned'] = 0
        for i, page in enumerate(reader.pages[:100]):
            try:
                text = page.extract_text() or ''
                scan_value(result, 'PDF page '+str(i+1), 'extracted text', text[:100000])
                result['structure']['page_text_scanned'] += 1
            except Exception as exc:
                result['warnings'].append('Page '+str(i+1)+' text extraction failed: '+tidy(exc))
        if len(reader.pages) > 100:
            result['warnings'].append('Only first 100 PDF pages scanned for text.')
    except Exception as exc:
        result['warnings'].append('PDF parser failed: '+type(exc).__name__+': '+tidy(exc))


def inspect(path):
    result = dict(filename=path.name, format=path.suffix.lower(), size_bytes=path.stat().st_size,
                  sha256=sha256(path), analyzed_at=datetime.now().astimezone().isoformat(timespec='seconds'),
                  integrity={}, structure={}, metadata={}, findings=[], warnings=[], findings_truncated=False)
    if path.suffix.lower() in ZIP_FORMATS:
        inspect_ooxml(path, result)
    elif path.suffix.lower() in ('.doc','.xls','.ppt'):
        inspect_ole(path, result)
    elif path.suffix.lower() == '.pdf':
        inspect_pdf(path, result)
    return result


def report(data):
    lines = ['UNIVERSAL OFFICE & PDF FORENSICS — TECHNICAL EXAMINATION REPORT', '='*72,
             'Examined file: '+data['filename'], 'File format: '+data['format'],
             'Analysis time: '+data['analyzed_at'], 'File size (bytes): '+str(data['size_bytes']),
             'SHA-256: '+data['sha256'], '',
             'Method: Local, read-only inspection of document containers, metadata,',
             'structure and selected software/AI-related strings.',
             'Privacy: Original filenames and metadata may contain personal information.',
             'Reports should be stored with appropriate access restrictions.']
    def section(name, obj):
        lines.extend(['',name,'-'*len(name)])
        if not obj:
            lines.append('No information extracted.')
        elif isinstance(obj, dict):
            for k,v in obj.items():
                if isinstance(v, dict):
                    lines.append(str(k)+':')
                    for a,b in v.items():
                        lines.append('  '+tidy(a,150)+': '+tidy(b,1000))
                else:
                    lines.append(str(k)+': '+tidy(v,1000))
        else:
            lines.extend(str(v) for v in obj)
    section('1. CONTAINER AND INTEGRITY', data['integrity'])
    section('2. DOCUMENT STRUCTURE', data['structure'])
    section('3. DOCUMENT METADATA', data['metadata'])
    lines.extend(['','4. SOFTWARE AND AI-RELATED STRING FINDINGS','-'*43])
    if not data['findings']:
        lines.append('No configured markers were found in the inspected content.')
    for i, f in enumerate(data['findings'], 1):
        lines.extend(['', 'Finding '+str(i), 'Marker: '+f['marker'], 'Description: '+f['description'],
                      'Location: '+f['location'], 'Field: '+f['field'], 'Classification: '+f['level'],
                      'Context: '+f['context'], 'Interpretation: '+f['interpretation']])
    if data['findings_truncated']:
        lines.append('Finding limit reached; additional matches were not recorded.')
    section('5. WARNINGS AND COVERAGE LIMITATIONS', data['warnings'] or ['No extraction warnings recorded.'])
    lines.extend(['', '6. EVIDENCE-BASED TECHNICAL CONCLUSION', '-'*38])
    fs = data['findings']
    strong = [f for f in fs if f['level'].startswith('STRONG:')]
    meta_software = [f for f in fs if f['marker'] not in AI_MARKERS and
                     (f['level'].startswith('SIGNIFICANT:') or f in strong)]
    ai = [f for f in fs if f['marker'] in AI_MARKERS]
    lines.append('Recorded marker findings: '+str(len(fs)))
    # TotalTime is the application-recorded editing duration in minutes, not
    # a verified stopwatch or a measure of all time spent preparing the work.
    app = data.get('metadata', {}).get('docProps/app.xml', {})
    def numeric(name):
        try:
            return int(str(app.get(name, '')).strip())
        except (ValueError, TypeError):
            return None
    total_minutes = numeric('TotalTime')
    pages = numeric('Pages')
    words = numeric('Words')
    characters = numeric('Characters')
    if total_minutes is not None:
        lines.append('RECORDED EDITING TIME ANALYSIS')
        lines.append('Application metadata TotalTime: '+str(total_minutes)+' minutes.')
        for name, value in (('Pages', pages), ('Words', words), ('Characters', characters)):
            if value is not None:
                lines.append('Application metadata '+name+': '+str(value)+'.')
        if total_minutes > 0 and words is not None:
            lines.append('Implied words per recorded editing minute: '+format(words/total_minutes, '.1f')+'.')
        if total_minutes > 0 and characters is not None:
            lines.append('Implied characters per recorded editing minute: '+format(characters/total_minutes, '.1f')+'.')
        if total_minutes <= 5 and (words is not None and words >= 500 or characters is not None and characters >= 3000):
            lines.append('Assessment: SUBSTANTIAL DOCUMENT CONTENT WITH VERY SHORT RECORDED EDITING TIME.')
            lines.append('This combination warrants investigation of bulk insertion, document import,')
            lines.append('template reuse, automated generation, or editing outside the measured file.')
        lines.append('Interpretation: TotalTime is an application-maintained metadata value;')
        lines.append('it does not measure all drafting, research, editing in other files, or')
        lines.append('time spent before content was pasted/imported. It is not a verified')
        lines.append('creation-duration measurement. Page and word counts are also stored metadata.')
    if strong:
        markers = sorted(set(f['marker'] for f in strong))
        lines.append('Assessment: STRONG METADATA ATTRIBUTION OF PROGRAMMATIC GENERATION')
        lines.append('Explicit generation statements identify: '+', '.join(markers)+'.')
        for f in strong:
            lines.append('Evidence: '+f['location']+' / '+f['field']+' = '+f['context'])
        for marker in markers:
            supporting = [f for f in meta_software if f['marker'] == marker and f not in strong]
            for f in supporting:
                lines.append('Corroborating metadata: '+f['location']+' / '+f['field']+' = '+f['context'])
        lines.append('Interpretation: The document metadata explicitly attributes its generation')
        lines.append('to the named software. This is strong evidence of programmatic document')
        lines.append('generation using the identified software, as recorded in the file.')
        lines.append('This is consistent with a Python program, an automated software workflow,')
        lines.append('or an AI-assisted workflow using the named library. The file does not')
        lines.append('by itself distinguish which of those workflows supplied the content.')
    elif meta_software:
        lines.append('Assessment: SOFTWARE IDENTIFIERS PRESENT IN METADATA')
        for f in meta_software:
            lines.append('Evidence: '+f['marker']+' at '+f['location']+' / '+f['field']+' = '+f['context'])
        lines.append('Interpretation: These metadata entries associate the file with named software,')
        lines.append('and provide technical evidence of software involvement. The recorded field determines whether creation or subsequent processing is indicated.')
    elif fs:
        lines.append('Assessment: STRING REFERENCES FOUND; NO EXPLICIT GENERATION ATTRIBUTION')
        lines.append('Interpretation: The recorded strings require examination in their locations;')
        lines.append('content mentions alone are not evidence of a generation workflow.')
    else:
        lines.append('Assessment: NO CONFIGURED SOFTWARE OR AI STRINGS DETECTED')
        lines.append('Interpretation: This does not establish how the document was created.')
    if ai:
        lines.append('AI-related names: '+', '.join(sorted(set(f['marker'] for f in ai)))+'.')
        lines.append('Examine each location and field to determine whether the name is an application identifier, integration record, or content mention.')
    lines.extend(['', 'TECHNICAL SCOPE:',
                  'Metadata records and file structure are reported as found in the examined file.',
                  'A generation-library attribution is evidence of a software-based workflow; the report does not identify the operator.',
                  'RSID counts describe stored revision identifiers, not the number of editing sessions.',
                  '', '='*72, 'END OF REPORT', '='*72, ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--file', help='Examine one document')
    group.add_argument('--input-dir', default='.', help='Directory to scan (non-recursive, default: current directory)')
    parser.add_argument('--output-dir', default='./forensics-reports', help='Report directory')
    args = parser.parse_args()
    output = pathlib.Path(args.output_dir).expanduser().resolve()
    if args.file:
        paths = [pathlib.Path(args.file).expanduser().resolve()]
        if not paths[0].is_file() or paths[0].suffix.lower() not in EXTENSIONS:
            parser.error('Input file missing or unsupported format')
    else:
        source = pathlib.Path(args.input_dir).expanduser().resolve()
        if not source.is_dir():
            parser.error('Input directory not found')
        paths = sorted((p for p in source.iterdir() if p.is_file() and p.suffix.lower() in EXTENSIONS and not p.name.startswith('~$')), key=lambda p:p.name.casefold())
    if not paths:
        parser.error('No supported documents found')
    output.mkdir(parents=True, exist_ok=True)
    success = failure = 0
    for path in paths:
        try:
            data = inspect(path)
            # Extension included in report name to prevent collisions between .doc and .docx.
            target = output / (path.name + '_report.txt')
            if target.resolve() == path.resolve():
                raise ValueError('Report path collides with input file')
            target.write_text(report(data), encoding='utf-8')
            print('OK:', path.name, '->', target)
            success += 1
        except Exception as exc:
            print('FAILED:', path.name, type(exc).__name__, tidy(exc), file=sys.stderr)
            failure += 1
    print('Completed:', success, 'successful,', failure, 'failed')
    return 1 if failure else 0


if __name__ == '__main__':
    sys.exit(main())
